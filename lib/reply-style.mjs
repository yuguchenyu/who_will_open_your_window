import {REPLY_STYLES} from '../public/reply-styles.mjs';
import {ApiError} from './errors.mjs';
export function replyStyleOf(value='natural'){
 if(!REPLY_STYLES.some(s=>s.id===value))throw new ApiError('请选择有效的回复选项风格。');
 return value;
}
export function replyStylePrompt(value){
 const style=replyStyleOf(value);
 const instructions={
  natural:'自然日常：像朋友在即时聊天中随手发的一句话，口语、平实、不端着。可以简短接话，不必句句问问题。',
  humorous:'轻松幽默：根据当前话题做一点轻巧的玩笑或自嘲，不用硬梗、油腻情话，不嘲讽对方。对方难过、生气或表达边界时先认真回应，不拿情绪开玩笑。',
  warm:'温柔关心：具体地接住对方说的事，用自然关心代替空泛安慰。不要心理咨询腔，不假设亲密关系，不轻易说“我永远陪着你”。',
  brief:'直接简短：能一句说清就一句，通常 5–20 个汉字。表达清楚、坦诚但不冷漠，不写解释段落或连续追问。'
 };
 return `【回复选项写作规则】当前风格 ${style}：${instructions[style]}
只调整 suggestions 的说话方式，不能改变对话意图解释或对方情绪的判断标准。
建议应像当前用户自己会发出的微信短消息：通常 5–35 个汉字、最多两句，必要时可稍长，但不超过接口规定的 100 字。
直接承接最新一句和已知上下文，先确认谁说过、做过什么；用具体接话代替“听起来很不错”“我能理解你的感受”等通用开头。不要每条都复述对方的话再反问，不要三条同义改写。
三个选项提供不同且自然的下一步：可以简短回应、顺着话题接一句、温和确认或转话题；不是每条都要提问。没有需要追问的信息就不硬问。
不写客服话术、分析口吻、长篇说教、文艺独白或括号动作描写。不强行用网络梗、语气词、叠词、错别字或表情来伪装真人；表情至多一个且按语境使用，不要求每条都有。
不编造当前用户的经历、兴趣、感受、安排、照片或承诺；未知事实不能写成“我也……”。若当前用户之前分享了自己遇到的小猫、对方说想看，应继续承接用户分享，不反过来问对方那只小猫。
风格是可编辑的写作建议，不能替用户发送。尊重拒绝，不施压，不诱导对方透露隐私。`;
}
